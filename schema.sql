-- Von Visual Designs client progress portal
-- Run this in Supabase Dashboard > SQL Editor.
-- Replace the admin email below if your admin email ever changes.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  client_name text not null default '',
  client_email text not null,
  project_name text not null,
  description text not null default '',
  progress_percent integer not null default 0 check (progress_percent between 0 and 100),
  stage text not null default 'Getting started',
  progress_notes text not null default '',
  designer_name text not null default 'Isaac',
  designer_email text not null default 'isaac@vonvisualdesigns.com',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists projects_client_email_lower_idx
on public.projects (lower(client_email));

alter table public.projects enable row level security;

-- Only this email can use the designer admin functions.
create or replace function public.is_von_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'isaac@vonvisualdesigns.com';
$$;

grant execute on function public.is_von_admin() to authenticated;

drop policy if exists "Clients can read their own project" on public.projects;
create policy "Clients can read their own project"
on public.projects for select to authenticated
using (lower(client_email) = lower(coalesce(auth.jwt() ->> 'email', '')) or public.is_von_admin());

drop policy if exists "Admin can add projects" on public.projects;
create policy "Admin can add projects"
on public.projects for insert to authenticated
with check (public.is_von_admin());

drop policy if exists "Admin can update projects" on public.projects;
create policy "Admin can update projects"
on public.projects for update to authenticated
using (public.is_von_admin())
with check (public.is_von_admin());

drop policy if exists "Admin can delete projects" on public.projects;
create policy "Admin can delete projects"
on public.projects for delete to authenticated
using (public.is_von_admin());

grant select, insert, update, delete on public.projects to authenticated;
grant usage, select on sequence public.projects_id_seq to authenticated;
